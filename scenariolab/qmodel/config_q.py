# ---------------------------------------------------------------- release lags of the raw inputs
# KNOWN LAG in months after the END of the reference period: a value for a period ending in month E is known at the
# START of month E + 1 + lag. A monthly market price (lag 0) is known at the start of the next month; CPI (lag 1) is
# published in the middle of the next month, so the start of month t knows CPI through t - 2. A quarterly series'
# reference period ends in the quarter's last month; the project's RELEASE_LAGS (months after the quarter's FIRST
# month, published by that month's end) translate as lag = RELEASE_LAGS - 2 (CP 5 -> 3: a quarter is known at the
# start of the fourth month after it ends). Start-of-quarter states and the __known columns use only these
# observations; the truncation test rebuilds the panel from inputs cut at these lags.
def _rl(series_id: str) -> int:
    return int(config.RELEASE_LAGS[series_id]) - 2


