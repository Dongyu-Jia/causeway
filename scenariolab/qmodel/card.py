"""The model card (SIM_DESIGN §3.3, §3.4, Appendix A) and the QTable/1 contract (Appendix B).

card.json (generated by tools/build_model_card.py from qmodel/schema.json plus the design's overrides) has one row
per variable, 101 in all: x_q (52 fields + 5 policy shocks), s_q (22), c_q anchors (5), outputs (5) and views (12).
Each row carries the Appendix A columns (字段, 中文名, 槽位, 同期/前定, 时点, 内生性, 到资产的路径, 翻译器, 核心因子层,
金融条件, 单位, 起始, 发布滞后, 注) under English keys, and machine fields: group (x / u / s / c / y / v), endo and
timing codes, the translator permission code, L0 / financial-conditions roles, the quarterly-panel columns of the row
and, for E1 / E1c / E2 fields, the Chinese keywords a quote must name (SIM_DESIGN §7.3).

The LLM's output schema is the model's input schema: qtable_json_schema() generates QTable/1 from the card, so its
x-field enum is exactly the card's x_q set. prompt_fields() gives the translator's compact field list (production or
test mode). The blind schema view for the translator is tools/schema_view.py -> schema_view.json.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import config_q as cq

# Appendix A columns: (key, 中文列名)
COLUMNS = [("id", "字段"), ("zh", "中文名"), ("slot", "槽位"), ("lead", "同期/前定"), ("timing", "时点"),
           ("endo", "内生性"), ("route", "到资产的路径"), ("translator", "翻译器"), ("factor_core", "核心因子层"),
           ("fc", "金融条件"), ("unit", "单位"), ("first", "起始"), ("lag", "发布滞后"), ("note", "注")]
GROUP_COUNTS = {"x": 52, "u": 5, "s": 22, "c": 5, "y": 5, "v": 12}
GROUP_NAMES = {"x": "x_q 字段", "u": "x_q 政策冲击（干预）", "s": "s_q 状态", "c": "c_q 锚", "y": "输出", "v": "视图"}
PERMISSIONS = {"free": "可写", "stated_only": "只在文字明说时（数字或定性幅度）",
               "raw_or_shock": "写原始值（因经济而动）或写冲击 u（干预）",
               "intervention_only": "只在文字写明“干预”时（数字或定性幅度）", "default": "可写（有默认值）",
               "data": "不可写（数据）；反事实起点只在实验室", "read_only": "只读", "never": "不可写"}
YEAR_TOKEN = re.compile(r"(?<![0-9])(?:19|20)[0-9]{2}(?![0-9])")
QUARTER_TOKEN = re.compile(r"(?<![0-9A-Za-z])Q[1-4](?![0-9])")


# ---------------------------------------------------------------- load / validate

def load_card(path: Path | None = None) -> dict:
    return json.loads(Path(path or cq.CARD_PATH).read_text(encoding="utf-8"))


def load_schema(path: Path | None = None) -> dict:
    return json.loads(Path(path or cq.SCHEMA_PATH).read_text(encoding="utf-8"))


def rows(card: dict, group: str | None = None) -> list[dict]:
    return [r for r in card["rows"] if group is None or r["group"] == group]


def ids(card: dict, group: str) -> list[str]:
    return [r["id"] for r in rows(card, group)]


def row(card: dict, field_id: str) -> dict:
    for r in card["rows"]:
        if r["id"] == field_id:
            return r
    raise KeyError(f"字段不存在：{field_id}")


def x_fields(card: dict) -> list[str]:
    """The 52 x_q schema fields (QTable rows[].x)."""
    return ids(card, "x")


def shocks(card: dict) -> list[str]:
    return ids(card, "u")


def stated_only_fields(card: dict) -> list[str]:
    """E1 / E1c / E2 fields: written only when the text states them, with a quote naming the variable."""
    return [r["id"] for r in rows(card, "x") if r["permission"] == "stated_only"]


def panel_columns(card: dict) -> dict[str, list[str]]:
    """{card row: [quarterly-panel columns]} for every row with a measured series (x, s, y, v)."""
    return {r["id"]: list(r["panel"]) for r in card["rows"] if r["panel"]}


def validate_card(card: dict) -> list[str]:
    """Structural problems of a card (empty list = valid): counts per group, unique ids, the Appendix A columns,
    permissions, L0 and financial-conditions roles, panel columns of measured rows, keywords of stated-only fields."""
    problems = []
    seen = set()
    for r in card.get("rows", []):
        if r["id"] in seen:
            problems.append(f"duplicate id {r['id']}")
        seen.add(r["id"])
        for key, _ in COLUMNS:
            if key not in r:
                problems.append(f"{r['id']}: missing column {key}")
        if r.get("permission") not in PERMISSIONS:
            problems.append(f"{r['id']}: unknown permission {r.get('permission')!r}")
        if r["group"] in ("x", "s", "y", "v") and not r.get("panel"):
            problems.append(f"{r['id']}: no quarterly-panel column")
        if r.get("permission") == "stated_only" and not r.get("keywords"):
            problems.append(f"{r['id']}: stated-only field without keywords")
    counts = {g: sum(r["group"] == g for r in card.get("rows", [])) for g in GROUP_COUNTS}
    if counts != GROUP_COUNTS:
        problems.append(f"group counts {counts} != {GROUP_COUNTS}")
    l0 = {r["id"] for r in card.get("rows", []) if r.get("l0")}
    if l0 != set(cq.L0_FIELDS):
        problems.append(f"L0 rows {sorted(l0)} != config_q.L0_FIELDS")
    fc_req = {r["id"] for r in card.get("rows", []) if r.get("fc_role") == "required_one"}
    if fc_req != {"d_gz", "d_spread"}:
        problems.append(f"financial-conditions rows {sorted(fc_req)}")
    if set(shocks(card)) != set(cq.SHOCKS):
        problems.append("shock rows differ from config_q.SHOCKS")
    return problems


# ---------------------------------------------------------------- QTable/1 (SIM_DESIGN Appendix B; design/d04)

def _entry() -> dict:
    return {"type": "object", "additionalProperties": False,
            "properties": {"value": {"type": "number"}, "sd": {"type": "number", "exclusiveMinimum": 0},
                           "sign": {"enum": ["+", "-", "0"]}, "size": {"enum": list(cq.SIZE_BINS)},
                           "min": {"type": "number"}, "max": {"type": "number"},
                           "src": {"enum": list(cq.SOURCES_OF_VALUES)},
                           "quote": {"type": "string", "maxLength": cq.QUOTE_MAX}},
            "required": ["src", "quote"]}


def qtable_json_schema(card: dict | None = None) -> dict:
    """The QTable/1 JSON schema (draft 2020-12), generated from the card: rows[].x has exactly the card's x_q fields,
    rows[].u its policy shocks; an absent field means "not stated" (the model completes it)."""
    card = card or load_card()
    x_ids = sorted(i for i in x_fields(card) if i != "x_oil_cause")
    u_ids = shocks(card)
    quote = {"type": "string", "maxLength": cq.QUOTE_MAX}
    row_schema = {
        "type": "object", "additionalProperties": False,
        "properties": {
            "q": {"type": "integer", "minimum": 1},
            "x": {"type": "object", "additionalProperties": False,
                  "properties": {**{k: _entry() for k in x_ids},
                                 "x_oil_cause": {"type": "object", "additionalProperties": False,
                                                 "properties": {"value": {"enum": list(row(card, "x_oil_cause")["enum"])},
                                                                "src": {"enum": ["stated", "stated_qual"]},
                                                                "quote": quote},
                                                 "required": ["value", "src", "quote"]}}},
            "u": {"type": "object", "additionalProperties": False, "properties": {k: _entry() for k in u_ids}},
            "fc": {"type": "object", "additionalProperties": False,
                   "properties": {"stance": {"enum": list(cq.FC_STANCES)}, "quote": quote}, "required": ["stance"]}},
        "required": ["q", "x", "fc"]}
    quarters = {"type": "array", "items": {"type": "integer"}}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema", "title": "QTable/1",
        "description": "季度情景表：LLM 的输出 = 季度模型的输入。null/缺省 = 文字没有给（模型补全）。",
        "type": "object", "additionalProperties": False,
        "properties": {
            "schema": {"const": cq.QTABLE_SCHEMA_ID}, "model_card": {"type": "string"},
            "n_quarters": {"type": "integer", "minimum": 1, "maximum": cq.QTABLE_MAX_QUARTERS},
            "rows": {"type": "array", "items": row_schema},
            "c_q": {"type": "object", "additionalProperties": False, "properties": {
                "anchors": {"type": "object", "additionalProperties": False,
                            "properties": {a: {"type": "object", "additionalProperties": False,
                                               "properties": {"value": {"type": "number"},
                                                              "from_q": {"type": "integer", "minimum": 1},
                                                              "quote": quote},
                                               "required": ["value", "quote"]} for a in cq.QTABLE_ANCHORS}},
                "announced": {"type": "array", "items": {"type": "object", "additionalProperties": False,
                                                         "properties": {
                    "field": {"enum": x_ids}, "quarters": quarters,
                    "values": {"type": "array", "items": {"type": ["number", "null"]}}, "sd": {"type": "number"},
                    "quote": quote}, "required": ["field", "quarters", "quote"]}},
                "constraints": {"type": "array", "items": {"type": "object", "additionalProperties": False,
                                                           "properties": {
                    "kind": {"enum": ["sum", "mean", "yoy", "level", "range"]},
                    "field": {"enum": x_ids + list(cq.CONSTRAINT_STATES)},
                    "quarters": quarters, "value": {"type": "number"}, "sd": {"type": "number"},
                    "min": {"type": "number"}, "max": {"type": "number"}, "quote": quote},
                    "required": ["kind", "field", "quarters", "quote"]}},
                "valuation": {"type": "array", "items": {"type": "object", "additionalProperties": False,
                                                         "properties": {
                    "quarters": quarters, "mode": {"enum": list(cq.VALUATION_MODES)}, "direction": {"enum": ["+", "-"]},
                    "size": {"enum": list(cq.VALUATION_SIZES)},
                    "reversion_half_life_years": {"type": "number", "minimum": cq.MIN_REVERSION_HALF_LIFE_YEARS},
                    "quote": quote}, "required": ["quarters", "mode", "quote"]}},
                "regime": {"type": "array", "items": {"type": "object", "additionalProperties": False, "properties": {
                    "quarters": quarters, "label": {"enum": list(cq.REGIME_LABELS)},
                    "share": {"type": "number", "minimum": 0, "maximum": 1}, "quote": quote},
                    "required": ["quarters", "label", "share", "quote"]}}}},
            "events": {"type": "array", "items": {"type": "object", "additionalProperties": False, "properties": {
                "text": {"type": "string", "maxLength": 200}, "quarters": quarters,
                "templates": {"type": "array", "items": {"type": "string", "pattern": "^G[0-9]{2}$"}},
                "channels": {"type": "array", "items": {"enum": x_ids + u_ids + ["x_oil_cause"]}},
                "generic_footprint": {"type": "boolean"}, "how_decomposed": {"type": "string", "maxLength": 200}},
                "required": ["text", "quarters", "channels", "generic_footprint", "how_decomposed"]}},
            "notes": {"type": "array", "items": {"type": "string", "maxLength": 200}}},
        "required": ["schema", "n_quarters", "rows", "c_q", "events"]}


def qtable_fields(qschema: dict) -> dict[str, set]:
    """The field sets a QTable schema accepts: x (rows[].x), u (rows[].u), anchors (c_q.anchors)."""
    rp = qschema["properties"]["rows"]["items"]["properties"]
    return {"x": set(rp["x"]["properties"]), "u": set(rp["u"]["properties"]),
            "anchors": set(qschema["properties"]["c_q"]["properties"]["anchors"]["properties"])}


# ---------------------------------------------------------------- translator prompt sections (SIM_DESIGN §7.2)

def year_tokens(text: str) -> list[str]:
    """Calendar-year tokens (19xx / 20xx) in a text: the blind protocol forbids them in test mode."""
    return YEAR_TOKEN.findall(text)


def prompt_fields(card: dict | None = None, mode: str = "production") -> str:
    """The prompt's field section: one compact line per x_q field, policy shock and c_q anchor (id | 中文名 | 单位 |
    时点 | 内生性 | 翻译器 [| 金融条件]). Test mode drops the notes and first quarters (no dates) and checks that no
    year token remains."""
    if mode not in ("production", "test"):
        raise ValueError(f"mode must be production or test, not {mode!r}")
    card = card or load_card()
    out = ["字段 | 中文名 | 单位 | 时点 | 内生性 | 翻译器 | 金融条件"]
    for g in ("x", "u", "c"):
        out.append(f"# {GROUP_NAMES[g]}")
        for r in rows(card, g):
            parts = [r["id"], r["zh"], r["unit"], r["timing"], r["endo"], r["translator"], r["fc"] or "—"]
            if g == "x" and r.get("enum"):
                parts.append("取值 " + " / ".join(r["enum"]))
            if mode == "production" and r["note"]:
                parts.append("注：" + r["note"])
            out.append(" | ".join(parts))
    out.append("# 定性幅度（该字段季度变动的训练期标准差）")
    out.append("；".join(f"{k} = {v:g} sd" for k, v in cq.SIZE_BINS.items()))
    out.append("# 金融条件（每个季度必填）：" + " / ".join(cq.FC_STANCES))
    text = "\n".join(out)
    if mode == "test" and year_tokens(text):
        raise ValueError(f"test-mode field section contains year tokens: {sorted(set(year_tokens(text)))}")
    return text
